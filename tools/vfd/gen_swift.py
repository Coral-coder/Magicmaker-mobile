#!/usr/bin/env python3
"""Emit the VFD glyph bitmaps as Swift.

    python3 tools/vfd/gen_swift.py OUT.swift

Writes `enum VFDGlyphMetrics` (per-size width/height/ascent/advance/line) and
`enum VFDGlyphs { static let small/mid/big: [UInt32: [UInt32]] }` keyed by
Unicode scalar, rows top to bottom, bit 0 = leftmost pixel, plus the hollow-box
fallback for each size. After writing, the file is re-parsed and compared with
vfd_font.GLYPHS; any mismatch exits non-zero.
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vfd_font  # noqa: E402

ORDER = ("small", "mid", "big")


def _hex_digits(width):
    return max(2, (width + 3) // 4)


def _char_comment(cp):
    ch = chr(cp)
    if ch == " ":
        return "(space)"
    return ch


def _rows_literal(rows, digits):
    return "[" + ", ".join("0x%0*X" % (digits, r) for r in rows) + "]"


def emit_swift():
    out = []
    w = out.append
    w("// Generated by tools/vfd/gen_swift.py from tools/vfd/vfd_font.py. Do not edit by hand.")
    w("//")
    w("// VFD dot-matrix glyphs. Each glyph is `height` rows, top to bottom; in each row")
    w("// bit 0 is the leftmost pixel. small is the hand-made 5x7 set (+2 descender rows),")
    w("// mid is Scale2x (EPX) of small, big is Scale3x (AdvMAME3x) of small.")
    w("// The glyph box top is the text row r; the last body row (the baseline) is")
    w("// r + ascent - 1, and the descender rows follow it.")
    w("")
    w("enum VFDGlyphMetrics {")
    w("    struct Size: Equatable {")
    w("        let width: Int    // glyph box width in cells")
    w("        let height: Int   // glyph box height in cells (body + descender)")
    w("        let ascent: Int   // body rows, the last one on the baseline")
    w("        let advance: Int  // cells from one character to the next")
    w("        let line: Int     // cells from one text line to the next")
    w("    }")
    w("")
    for size in ORDER:
        m = vfd_font.SIZES[size]
        w("    static let %s = Size(width: %d, height: %d, ascent: %d, advance: %d, line: %d)"
          % (size, m["w"], m["h"], m["ascent"], m["advance"], m["line"]))
    w("}")
    w("")
    w("enum VFDGlyphs {")
    for size in ORDER:
        m = vfd_font.SIZES[size]
        digits = _hex_digits(m["w"])
        w("    /// Hollow box drawn for characters without a glyph (%s)." % size)
        w("    static let %sFallback: [UInt32] = %s"
          % (size, _rows_literal(vfd_font.FALLBACK[size], digits)))
        w("")
    for i, size in enumerate(ORDER):
        m = vfd_font.SIZES[size]
        digits = _hex_digits(m["w"])
        table = vfd_font.GLYPHS[size]
        w("    /// %s: %dx%d cells, %d glyphs." % (size, m["w"], m["h"], len(table)))
        w("    static let %s: [UInt32: [UInt32]] = [" % size)
        for cp in sorted(table):
            w("        0x%04X: %s, // %s" % (cp, _rows_literal(table[cp], digits), _char_comment(cp)))
        w("    ]")
        if i != len(ORDER) - 1:
            w("")
    w("}")
    w("")
    return "\n".join(out)


_TABLE_RE = re.compile(r"static let (small|mid|big): \[UInt32: \[UInt32\]\] = \[\n(.*?)\n    \]", re.S)
_ENTRY_RE = re.compile(r"^\s*0x([0-9A-F]+): \[([^\]]*)\], // (.*)$")
_FALLBACK_RE = re.compile(r"static let (small|mid|big)Fallback: \[UInt32\] = \[([^\]]*)\]")
_METRIC_RE = re.compile(
    r"static let (small|mid|big) = Size\(width: (\d+), height: (\d+), ascent: (\d+), "
    r"advance: (\d+), line: (\d+)\)")


def _ints(lst):
    return [int(x.strip(), 16) for x in lst.split(",") if x.strip()]


def verify(text):
    """Re-parse emitted Swift and compare with vfd_font. Returns list of problems."""
    probs = []
    tables = {}
    for m in _TABLE_RE.finditer(text):
        size, body = m.group(1), m.group(2)
        entries = {}
        last = -1
        for line in body.split("\n"):
            e = _ENTRY_RE.match(line)
            if not e:
                probs.append("%s: unparsed line %r" % (size, line))
                continue
            cp = int(e.group(1), 16)
            if cp <= last:
                probs.append("%s: U+%04X out of order" % (size, cp))
            last = cp
            comment = e.group(3)
            want = "(space)" if cp == 0x20 else chr(cp)
            if comment != want:
                probs.append("%s: U+%04X comment %r != %r" % (size, cp, comment, want))
            entries[cp] = _ints(e.group(2))
        tables[size] = entries
    for size in ORDER:
        got = tables.get(size)
        if got is None:
            probs.append("missing table %s" % size)
            continue
        want = vfd_font.GLYPHS[size]
        if set(got) != set(want):
            probs.append("%s: codepoint sets differ (%d vs %d)" % (size, len(got), len(want)))
        for cp, rows in want.items():
            if got.get(cp) != rows:
                probs.append("%s: U+%04X rows differ" % (size, cp))
    fallbacks = {m.group(1): _ints(m.group(2)) for m in _FALLBACK_RE.finditer(text)}
    for size in ORDER:
        if fallbacks.get(size) != vfd_font.FALLBACK[size]:
            probs.append("%s: fallback differs" % size)
    metrics = {m.group(1): tuple(int(g) for g in m.groups()[1:]) for m in _METRIC_RE.finditer(text)}
    for size in ORDER:
        s = vfd_font.SIZES[size]
        if metrics.get(size) != (s["w"], s["h"], s["ascent"], s["advance"], s["line"]):
            probs.append("%s: metrics differ" % size)
    return probs


def main(argv):
    if len(argv) != 1 or argv[0].startswith("-"):
        print("usage: gen_swift.py OUT.swift", file=sys.stderr)
        return 2
    path = argv[0]
    text = emit_swift()
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    with open(path, encoding="utf-8") as f:
        probs = verify(f.read())
    if probs:
        for p in probs:
            print("MISMATCH:", p, file=sys.stderr)
        return 1
    n = len(vfd_font.GLYPHS["small"])
    print("wrote %s (%d glyphs x 3 sizes, verified against GLYPHS)" % (path, n))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
