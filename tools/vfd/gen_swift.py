#!/usr/bin/env python3
"""Emit the VFD glyph bitmaps as Swift.

    python3 tools/vfd/gen_swift.py ios/MagicMaker/VFD/VFDGlyphs.swift

Writes `enum VFDGlyphs` (Foundation-free Swift):

    Metrics, smallMetrics / midMetrics / bigMetrics      vfd_font.SIZES
    smallFallback / midFallback / bigFallback: [UInt32]  the hollow box for unknown characters
    scalars: [UInt32]                                    the Unicode scalars that have a glyph, ascending
    smallRows / midRows / bigRows: [UInt32]              every glyph's rows, glyph after glyph in
                                                         `scalars` order: glyph i of a size is rows
                                                         i*height ..< (i+1)*height (top to bottom,
                                                         bit 0 = leftmost pixel)
    slotByScalar: [UInt32: Int], slot(_:) -> Int?        scalar -> glyph number, built at first use

Why flat arrays: a nested `[UInt32: [UInt32]]` dictionary literal of a few hundred entries can keep
the Swift type checker busy for minutes; homogeneous `[UInt32]` literals with an explicit element
type are checked in linear time, and the lookup table is filled by a loop at runtime instead.

After writing, the file is re-parsed and compared with vfd_font (GLYPHS, FALLBACK, SIZES); any
mismatch exits non-zero.
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vfd_font  # noqa: E402

ORDER = ("small", "mid", "big")


def _hex_digits(width):
    return max(2, (width + 3) // 4)


def _char_comment(cp):
    ch = chr(cp)
    if ch == " ":
        return "(space)"
    return ch


def _rows_text(rows, digits):
    return ", ".join("0x%0*X" % (digits, r) for r in rows)


def emit_swift():
    out = []
    w = out.append
    scalars = sorted(vfd_font.GLYPHS["small"])
    for size in ORDER:
        if sorted(vfd_font.GLYPHS[size]) != scalars:
            raise SystemExit("gen_swift: the sizes do not cover the same characters")
    w("// Generated by tools/vfd/gen_swift.py from tools/vfd/vfd_font.py. Do not edit by hand.")
    w("//")
    w("// VFD dot-matrix glyphs. Each glyph is `height` rows, top to bottom; in each row")
    w("// bit 0 is the leftmost pixel. small is the hand-made 5x7 set (+2 descender rows),")
    w("// mid is Scale2x (EPX) of small, big is Scale3x (AdvMAME3x) of small.")
    w("// The glyph box top is the text row r; the last body row (the baseline) is")
    w("// r + ascent - 1, and the descender rows follow it.")
    w("//")
    w("// Layout: `scalars` lists the characters that have a glyph, ascending. Glyph i of a size")
    w("// is rows i * height ..< (i + 1) * height of that size's flat row table. Flat [UInt32]")
    w("// literals keep the type checker fast; the scalar -> glyph table is built at first use.")
    w("")
    w("enum VFDGlyphs {")
    w("    struct Metrics: Equatable {")
    w("        let width: Int    // glyph box width in cells")
    w("        let height: Int   // glyph box height in cells (body + descender)")
    w("        let ascent: Int   // body rows, the last one on the baseline")
    w("        let advance: Int  // cells from one character to the next")
    w("        let line: Int     // cells from one text line to the next")
    w("    }")
    w("")
    for size in ORDER:
        m = vfd_font.SIZES[size]
        w("    static let %sMetrics = Metrics(width: %d, height: %d, ascent: %d, advance: %d, line: %d)"
          % (size, m["w"], m["h"], m["ascent"], m["advance"], m["line"]))
    w("")
    for size in ORDER:
        m = vfd_font.SIZES[size]
        w("    /// Hollow box drawn for characters without a glyph (%s)." % size)
        w("    static let %sFallback: [UInt32] = [%s]"
          % (size, _rows_text(vfd_font.FALLBACK[size], _hex_digits(m["w"]))))
    w("")
    w("    /// The %d characters that have a glyph, ascending." % len(scalars))
    w("    static let scalars: [UInt32] = [")
    for i in range(0, len(scalars), 12):
        w("        " + ", ".join("0x%04X" % cp for cp in scalars[i:i + 12]) + ",")
    w("    ]")
    for size in ORDER:
        m = vfd_font.SIZES[size]
        digits = _hex_digits(m["w"])
        table = vfd_font.GLYPHS[size]
        w("")
        w("    /// %s: %dx%d cells, %d rows per glyph." % (size, m["w"], m["h"], m["h"]))
        w("    static let %sRows: [UInt32] = [" % size)
        for cp in scalars:
            w("        %s, // %s" % (_rows_text(table[cp], digits), _char_comment(cp)))
        w("    ]")
    w("")
    w("    /// Glyph number of every scalar in `scalars`.")
    w("    static let slotByScalar: [UInt32: Int] = {")
    w("        var table: [UInt32: Int] = [:]")
    w("        var i: Int = 0")
    w("        for scalar in VFDGlyphs.scalars {")
    w("            table[scalar] = i")
    w("            i += 1")
    w("        }")
    w("        return table")
    w("    }()")
    w("")
    w("    /// Glyph number of a scalar, or nil when the font has no glyph for it.")
    w("    static func slot(_ scalar: UInt32) -> Int? {")
    w("        return slotByScalar[scalar]")
    w("    }")
    w("}")
    w("")
    return "\n".join(out)


_METRIC_RE = re.compile(
    r"static let (small|mid|big)Metrics = Metrics\(width: (\d+), height: (\d+), ascent: (\d+), "
    r"advance: (\d+), line: (\d+)\)")
_FALLBACK_RE = re.compile(r"static let (small|mid|big)Fallback: \[UInt32\] = \[([^\]]*)\]")
_SCALARS_RE = re.compile(r"static let scalars: \[UInt32\] = \[\n(.*?)\n    \]", re.S)
_ROWS_RE = re.compile(r"static let (small|mid|big)Rows: \[UInt32\] = \[\n(.*?)\n    \]", re.S)
_ROW_LINE_RE = re.compile(r"^        ((?:0x[0-9A-F]+, )*0x[0-9A-F]+), // (.*)$")


def _ints(text):
    return [int(x.strip(), 16) for x in text.split(",") if x.strip()]


def verify(text):
    """Re-parse emitted Swift and compare with vfd_font. Returns a list of problems."""
    probs = []
    metrics = {m.group(1): tuple(int(g) for g in m.groups()[1:]) for m in _METRIC_RE.finditer(text)}
    for size in ORDER:
        s = vfd_font.SIZES[size]
        if metrics.get(size) != (s["w"], s["h"], s["ascent"], s["advance"], s["line"]):
            probs.append("%s: metrics differ" % size)
    fallbacks = {m.group(1): _ints(m.group(2)) for m in _FALLBACK_RE.finditer(text)}
    for size in ORDER:
        if fallbacks.get(size) != vfd_font.FALLBACK[size]:
            probs.append("%s: fallback differs" % size)
    m = _SCALARS_RE.search(text)
    if not m:
        return probs + ["scalars table missing"]
    scalars = _ints(m.group(1))
    if scalars != sorted(set(scalars)):
        probs.append("scalars are not strictly ascending")
    for size in ORDER:
        if set(scalars) != set(vfd_font.GLYPHS[size]):
            probs.append("%s: codepoint sets differ" % size)
    tables = {}
    for m in _ROWS_RE.finditer(text):
        size, body = m.group(1), m.group(2)
        rows, comments = [], []
        for line in body.split("\n"):
            e = _ROW_LINE_RE.match(line)
            if not e:
                probs.append("%s: unparsed line %r" % (size, line))
                continue
            rows.append(_ints(e.group(1)))
            comments.append(e.group(2))
        tables[size] = (rows, comments)
    for size in ORDER:
        if size not in tables:
            probs.append("missing table %sRows" % size)
            continue
        rows, comments = tables[size]
        h = vfd_font.SIZES[size]["h"]
        if len(rows) != len(scalars):
            probs.append("%s: %d glyph lines for %d scalars" % (size, len(rows), len(scalars)))
            continue
        for cp, got, comment in zip(scalars, rows, comments):
            want = vfd_font.GLYPHS[size].get(cp)
            if len(got) != h or got != want:
                probs.append("%s: U+%04X rows differ" % (size, cp))
            if comment != _char_comment(cp):
                probs.append("%s: U+%04X comment %r" % (size, cp, comment))
    return probs


def main(argv):
    if len(argv) != 1 or argv[0].startswith("-"):
        print("usage: gen_swift.py OUT.swift", file=sys.stderr)
        return 2
    path = argv[0]
    text = emit_swift()
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    with open(path, encoding="utf-8") as f:
        probs = verify(f.read())
    if probs:
        for p in probs:
            print("MISMATCH:", p, file=sys.stderr)
        return 1
    n = len(vfd_font.GLYPHS["small"])
    print("wrote %s (%d glyphs x 3 sizes, verified against GLYPHS)" % (path, n))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
