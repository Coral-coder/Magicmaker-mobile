#!/usr/bin/env python3
"""Emit the VFD 5x7 dot-matrix face as a compact C table for the ESP32 firmware's OLED.

    python3 tools/vfd/gen_c.py            # writes the firmware header below
    python3 tools/vfd/gen_c.py OUT.h      # writes OUT.h
    python3 tools/vfd/gen_c.py --check    # exit 1 if the committed header is out of date

Default output: firmware/esp32-transmitter/vfd_font_5x7.h

The Heltec WiFi LoRa 32 V3 build of the transmitter draws its 128x64 OLED with the same face the
app's VFD theme uses: vfd_font.GLYPHS["small"] (5 wide, 9 tall including the 2 descender rows,
advance 6). The header holds ASCII 32-126 plus the hollow fallback box, nothing else, as

    static const uint8_t VFD5X7_GLYPHS[96][9] PROGMEM

glyph i = ASCII (32 + i) for i < 95, glyph 95 = the fallback box. Each glyph is 9 bytes, rows
top to bottom, bit 0 = leftmost pixel (the same bit order as vfd_font), so 864 bytes in all.

After writing, the file is re-parsed and compared with vfd_font (GLYPHS, FALLBACK, SIZES); any
mismatch exits non-zero. The output is deterministic (same input, same bytes).
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import vfd_font  # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
DEFAULT_OUT = os.path.join(REPO, "firmware", "esp32-transmitter", "vfd_font_5x7.h")

SIZE = "small"
FIRST, LAST = 32, 126                       # printable ASCII
CODEPOINTS = list(range(FIRST, LAST + 1))   # table order; the fallback box follows them
FALLBACK_INDEX = len(CODEPOINTS)


def _label(cp):
    """Comment text for a glyph line. Never ends in a backslash: a // comment ending in one
    would swallow the next table line."""
    if cp == 0x20:
        return "(space)"
    if cp == 0x5C:
        return "(backslash)"
    return chr(cp)


def _row_bytes(rows):
    return ", ".join("0x%02X" % r for r in rows)


def emit_c():
    m = vfd_font.SIZES[SIZE]
    w, h = m["w"], m["h"]
    if w > 8:
        raise SystemExit("gen_c: rows no longer fit in a byte")
    missing = [cp for cp in CODEPOINTS if cp not in vfd_font.GLYPHS[SIZE]]
    if missing:
        raise SystemExit("gen_c: vfd_font has no glyph for %s" % ", ".join("U+%04X" % c for c in missing))

    out = []
    put = out.append
    put("// Generated by tools/vfd/gen_c.py from tools/vfd/vfd_font.py. Do not edit by hand.")
    put("//")
    put("// The VFD 5x7 dot-matrix face (the app's VFD theme, size \"small\") for the OLED.")
    put("// Glyph box %dx%d: rows 0-%d are the body (capitals and digits use all %d), rows %d-%d the"
        % (w, h, m["ascent"] - 1, m["ascent"], m["ascent"], h - 1))
    put("// descender. Advance %d (column %d is always the gap), line pitch %d."
        % (m["advance"], w, m["line"]))
    put("// One glyph = %d bytes, rows top to bottom, bit 0 = leftmost pixel." % h)
    put("// Glyph i is ASCII (VFD5X7_FIRST + i) for i < %d; glyph VFD5X7_FALLBACK is the hollow box"
        % len(CODEPOINTS))
    put("// drawn for characters without a glyph.")
    put("")
    put("#pragma once")
    put("")
    put("#include <stdint.h>")
    put("#if defined(ARDUINO)")
    put("#include <Arduino.h>")
    put("#endif")
    put("#ifndef PROGMEM")
    put("#define PROGMEM")
    put("#endif")
    put("")
    put("#define VFD5X7_W        %d" % w)
    put("#define VFD5X7_H        %d" % h)
    put("#define VFD5X7_ASCENT   %d" % m["ascent"])
    put("#define VFD5X7_ADVANCE  %d" % m["advance"])
    put("#define VFD5X7_LINE     %d" % m["line"])
    put("#define VFD5X7_FIRST    %d" % FIRST)
    put("#define VFD5X7_LAST     %d" % LAST)
    put("#define VFD5X7_FALLBACK %d" % FALLBACK_INDEX)
    put("")
    put("static const uint8_t VFD5X7_GLYPHS[%d][VFD5X7_H] PROGMEM = {" % (len(CODEPOINTS) + 1))
    for cp in CODEPOINTS:
        put("  {%s}, // 0x%02X %s" % (_row_bytes(vfd_font.GLYPHS[SIZE][cp]), cp, _label(cp)))
    put("  {%s}, // fallback (hollow box)" % _row_bytes(vfd_font.FALLBACK[SIZE]))
    put("};")
    put("")
    return "\n".join(out)


_DEFINE_RE = re.compile(r"^#define (VFD5X7_[A-Z]+) +(\d+)$", re.M)
_TABLE_RE = re.compile(r"static const uint8_t VFD5X7_GLYPHS\[(\d+)\]\[VFD5X7_H\] PROGMEM = \{\n(.*?)\n\};", re.S)
_GLYPH_RE = re.compile(r"^  \{((?:0x[0-9A-F]{2}, )*0x[0-9A-F]{2})\}, // (?:0x([0-9A-F]{2}) (.+)|fallback \(hollow box\))$")


def verify(text):
    """Re-parse an emitted header and compare it with vfd_font. Returns a list of problems."""
    probs = []
    m = vfd_font.SIZES[SIZE]
    want_defs = {
        "VFD5X7_W": m["w"], "VFD5X7_H": m["h"], "VFD5X7_ASCENT": m["ascent"],
        "VFD5X7_ADVANCE": m["advance"], "VFD5X7_LINE": m["line"], "VFD5X7_FIRST": FIRST,
        "VFD5X7_LAST": LAST, "VFD5X7_FALLBACK": FALLBACK_INDEX,
    }
    defs = {k: int(v) for k, v in _DEFINE_RE.findall(text)}
    if defs != want_defs:
        probs.append("defines differ: %r" % defs)
    t = _TABLE_RE.search(text)
    if not t:
        return probs + ["glyph table missing"]
    if int(t.group(1)) != len(CODEPOINTS) + 1:
        probs.append("table declares %s glyphs" % t.group(1))
    lines = t.group(2).split("\n")
    if len(lines) != len(CODEPOINTS) + 1:
        return probs + ["%d glyph lines, expected %d" % (len(lines), len(CODEPOINTS) + 1)]
    mask = (1 << m["w"]) - 1
    for i, line in enumerate(lines):
        g = _GLYPH_RE.match(line)
        if not g:
            probs.append("unparsed line %r" % line)
            continue
        if line.endswith("\\"):
            probs.append("line %d ends in a backslash" % i)
        rows = [int(x, 16) for x in g.group(1).split(", ")]
        if i < len(CODEPOINTS):
            cp = CODEPOINTS[i]
            want = vfd_font.GLYPHS[SIZE][cp]
            if g.group(2) is None or int(g.group(2), 16) != cp or g.group(3) != _label(cp):
                probs.append("glyph %d is labelled %r, expected 0x%02X" % (i, line.split("// ")[-1], cp))
            name = "0x%02X" % cp
        else:
            want = vfd_font.FALLBACK[SIZE]
            if g.group(2) is not None:
                probs.append("last line is not the fallback box")
            name = "fallback"
        if len(rows) != m["h"] or rows != want:
            probs.append("%s: rows differ" % name)
        if any(r & ~mask for r in rows):
            probs.append("%s: a row is wider than %d pixels" % (name, m["w"]))
    return probs


def main(argv):
    check = False
    paths = []
    for a in argv:
        if a == "--check":
            check = True
        elif a.startswith("-"):
            print("usage: gen_c.py [OUT.h] [--check]", file=sys.stderr)
            return 2
        else:
            paths.append(a)
    if len(paths) > 1:
        print("usage: gen_c.py [OUT.h] [--check]", file=sys.stderr)
        return 2
    path = paths[0] if paths else DEFAULT_OUT
    text = emit_c()
    if text != emit_c():
        print("MISMATCH: output is not deterministic", file=sys.stderr)
        return 1
    if check:
        try:
            with open(path, encoding="utf-8", newline="") as f:
                current = f.read()
        except OSError as e:
            print("MISMATCH: cannot read %s: %s" % (path, e), file=sys.stderr)
            return 1
        probs = verify(current)
        if current != text:
            probs.append("%s is out of date: run python3 tools/vfd/gen_c.py" % path)
        if probs:
            for p in probs:
                print("MISMATCH:", p, file=sys.stderr)
            return 1
        print("%s is up to date" % path)
        return 0
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    with open(path, encoding="utf-8", newline="") as f:
        probs = verify(f.read())
    if probs:
        for p in probs:
            print("MISMATCH:", p, file=sys.stderr)
        return 1
    print("wrote %s (%d glyphs + fallback, %d bytes of rows, verified against GLYPHS)"
          % (path, len(CODEPOINTS), (len(CODEPOINTS) + 1) * vfd_font.SIZES[SIZE]["h"]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
