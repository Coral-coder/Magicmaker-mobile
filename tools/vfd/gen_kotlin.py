#!/usr/bin/env python3
"""Emit the VFD glyph bitmaps as Kotlin (the Android port of gen_swift.py).

    python3 tools/vfd/gen_kotlin.py            # writes the Android file below
    python3 tools/vfd/gen_kotlin.py OUT.kt     # writes OUT.kt
    python3 tools/vfd/gen_kotlin.py --check    # exit 1 if the committed Android file is out of date

Default output: android/app/src/main/java/com/magicmaker/android/ui/vfd/VFDGlyphs.kt

Writes `object VFDGlyphs` (package com.magicmaker.android.ui.vfd, Kotlin stdlib only):

    Metrics, smallMetrics / midMetrics / bigMetrics        vfd_font.SIZES
    smallFallback / midFallback / bigFallback: IntArray    the hollow box for unknown characters
    scalars: IntArray                                      the code points that have a glyph, ascending
    smallRows / midRows / bigRows: IntArray                every glyph's rows, glyph after glyph in
                                                           `scalars` order: glyph i of a size is rows
                                                           i*height until (i+1)*height (top to bottom,
                                                           bit 0 = leftmost pixel)
    slotIndex(cp): Int (-1 = none), slot(cp): Int?         code point -> glyph number (binary search)

Why strings: a JVM method (here the object's static initialiser) may hold at most 64 KB of
bytecode, and an `intArrayOf(...)` literal costs about 7 bytes per element; the three row tables
have ~6400 elements. So each table is one file-level `private const val` String of fixed-width hex
digits (one quoted piece per glyph, folded into a single constant by the compiler; file level
because Kotlin rejects an object property that reads a constant declared below it) that is decoded
once when the object is first used. Only `scalars` and the fallbacks (small) are array literals.

After writing, the file is re-parsed and compared with vfd_font (GLYPHS, FALLBACK, SIZES); any
mismatch exits non-zero. The output is deterministic (same input, same bytes).
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import vfd_font  # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
DEFAULT_OUT = os.path.join(REPO, "android", "app", "src", "main", "java", "com", "magicmaker", "android",
                           "ui", "vfd", "VFDGlyphs.kt")
PACKAGE = "com.magicmaker.android.ui.vfd"

ORDER = ("small", "mid", "big")
CONST = {"small": "VFD_GLYPH_SMALL_ROWS", "mid": "VFD_GLYPH_MID_ROWS", "big": "VFD_GLYPH_BIG_ROWS"}


def _hex_digits(width):
    return max(2, (width + 3) // 4)


def _char_comment(cp):
    ch = chr(cp)
    if ch == " ":
        return "(space)"
    return ch


def _rows_hex(rows, digits):
    return "".join("%0*X" % (digits, r) for r in rows)


def _rows_list(rows, digits):
    return ", ".join("0x%0*X" % (digits, r) for r in rows)


def emit_kotlin():
    out = []
    w = out.append
    scalars = sorted(vfd_font.GLYPHS["small"])
    for size in ORDER:
        if sorted(vfd_font.GLYPHS[size]) != scalars:
            raise SystemExit("gen_kotlin: the sizes do not cover the same characters")
        width = vfd_font.SIZES[size]["w"]
        if width > 31:
            raise SystemExit("gen_kotlin: %s glyphs are wider than an Int row" % size)
    w("// Generated by tools/vfd/gen_kotlin.py from tools/vfd/vfd_font.py. Do not edit by hand.")
    w("//")
    w("// VFD dot-matrix glyphs. Each glyph is `height` rows, top to bottom; in each row")
    w("// bit 0 is the leftmost pixel. small is the hand-made 5x7 set (+2 descender rows),")
    w("// mid is Scale2x (EPX) of small, big is Scale3x (AdvMAME3x) of small.")
    w("// The glyph box top is the text row r; the last body row (the baseline) is")
    w("// r + ascent - 1, and the descender rows follow it.")
    w("//")
    w("// Layout: `scalars` lists the code points that have a glyph, ascending. Glyph i of a size")
    w("// is rows i * height until (i + 1) * height of that size's flat row table. The row tables")
    w("// are stored as hex strings (one quoted piece per glyph, `digits` hex digits per row) and")
    w("// decoded once, which keeps the static initialiser far below the JVM's 64 KB method limit.")
    w("// Kotlin stdlib only (no android.*): also used by the JVM unit tests.")
    w("")
    w("package " + PACKAGE)
    w("")
    w("object VFDGlyphs {")
    w("    class Metrics(")
    w("        /** Glyph box width in cells. */")
    w("        val width: Int,")
    w("        /** Glyph box height in cells (body + descender). */")
    w("        val height: Int,")
    w("        /** Body rows, the last one on the baseline. */")
    w("        val ascent: Int,")
    w("        /** Cells from one character to the next. */")
    w("        val advance: Int,")
    w("        /** Cells from one text line to the next. */")
    w("        val line: Int,")
    w("    )")
    w("")
    for size in ORDER:
        m = vfd_font.SIZES[size]
        w("    val %sMetrics: Metrics = Metrics(width = %d, height = %d, ascent = %d, advance = %d, line = %d)"
          % (size, m["w"], m["h"], m["ascent"], m["advance"], m["line"]))
    w("")
    for size in ORDER:
        m = vfd_font.SIZES[size]
        w("    /** Hollow box drawn for characters without a glyph (%s). */" % size)
        w("    val %sFallback: IntArray = intArrayOf(%s)"
          % (size, _rows_list(vfd_font.FALLBACK[size], _hex_digits(m["w"]))))
    w("")
    w("    /** The %d code points that have a glyph, ascending. */" % len(scalars))
    w("    val scalars: IntArray = intArrayOf(")
    for i in range(0, len(scalars), 12):
        w("        " + ", ".join("0x%04X" % cp for cp in scalars[i:i + 12]) + ",")
    w("    )")
    w("")
    for size in ORDER:
        m = vfd_font.SIZES[size]
        w("    /** %s: %dx%d cells, %d rows per glyph. */" % (size, m["w"], m["h"], m["h"]))
        w("    val %sRows: IntArray = decode(%s, %d, %d)" % (size, CONST[size], _hex_digits(m["w"]), m["h"]))
    w("")
    w("    /** Glyph number of a code point, or -1 when the font has no glyph for it. */")
    w("    fun slotIndex(scalar: Int): Int {")
    w("        val i: Int = scalars.binarySearch(scalar)")
    w("        return if (i >= 0) i else -1")
    w("    }")
    w("")
    w("    /** Glyph number of a code point, or null when the font has no glyph for it. */")
    w("    fun slot(scalar: Int): Int? {")
    w("        val i: Int = slotIndex(scalar)")
    w("        return if (i >= 0) i else null")
    w("    }")
    w("")
    w("    private fun decode(hex: String, digits: Int, height: Int): IntArray {")
    w("        val n: Int = hex.length / digits")
    w("        check(n * digits == hex.length && n == scalars.size * height) { \"VFDGlyphs: bad row table\" }")
    w("        val out = IntArray(n)")
    w("        var k = 0")
    w("        for (i in 0 until n) {")
    w("            var v = 0")
    w("            for (d in 0 until digits) {")
    w("                v = (v shl 4) or Character.digit(hex[k], 16)")
    w("                k += 1")
    w("            }")
    w("            out[i] = v")
    w("        }")
    w("        return out")
    w("    }")
    w("}")
    for size in ORDER:
        m = vfd_font.SIZES[size]
        digits = _hex_digits(m["w"])
        table = vfd_font.GLYPHS[size]
        w("")
        w("/** VFDGlyphs.%sRows: %d hex digits per row, %d rows per glyph, glyphs in `scalars` order. */"
          % (size, digits, m["h"]))
        w("private const val %s: String =" % CONST[size])
        for k, cp in enumerate(scalars):
            joiner = " +" if k < len(scalars) - 1 else ""
            w("    \"%s\"%s // %s" % (_rows_hex(table[cp], digits), joiner, _char_comment(cp)))
    w("")
    return "\n".join(out)


_METRIC_RE = re.compile(
    r"val (small|mid|big)Metrics: Metrics = Metrics\(width = (\d+), height = (\d+), ascent = (\d+), "
    r"advance = (\d+), line = (\d+)\)")
_FALLBACK_RE = re.compile(r"val (small|mid|big)Fallback: IntArray = intArrayOf\(([^)]*)\)")
_SCALARS_RE = re.compile(r"val scalars: IntArray = intArrayOf\(\n(.*?)\n    \)", re.S)
_DECODE_RE = re.compile(r"val (small|mid|big)Rows: IntArray = decode\(([A-Z_]+), (\d+), (\d+)\)")
_CONST_RE = re.compile(r"^private const val ([A-Z_]+): String =\n((?:    .*\n?)+)", re.M)
_ROW_LINE_RE = re.compile(r"^    \"([0-9A-F]+)\"( \+)? // (.*)$")


def _ints(text):
    return [int(x.strip(), 16) for x in text.split(",") if x.strip()]


def verify(text):
    """Re-parse emitted Kotlin and compare with vfd_font. Returns a list of problems."""
    probs = []
    metrics = {m.group(1): tuple(int(g) for g in m.groups()[1:]) for m in _METRIC_RE.finditer(text)}
    for size in ORDER:
        s = vfd_font.SIZES[size]
        if metrics.get(size) != (s["w"], s["h"], s["ascent"], s["advance"], s["line"]):
            probs.append("%s: metrics differ" % size)
    fallbacks = {m.group(1): _ints(m.group(2)) for m in _FALLBACK_RE.finditer(text)}
    for size in ORDER:
        if fallbacks.get(size) != vfd_font.FALLBACK[size]:
            probs.append("%s: fallback differs" % size)
    m = _SCALARS_RE.search(text)
    if not m:
        return probs + ["scalars table missing"]
    scalars = _ints(m.group(1))
    if scalars != sorted(set(scalars)):
        probs.append("scalars are not strictly ascending")
    for size in ORDER:
        if set(scalars) != set(vfd_font.GLYPHS[size]):
            probs.append("%s: codepoint sets differ" % size)
    decodes = {m.group(1): (m.group(2), int(m.group(3)), int(m.group(4))) for m in _DECODE_RE.finditer(text)}
    consts = {m.group(1): m.group(2) for m in _CONST_RE.finditer(text)}
    for size in ORDER:
        s = vfd_font.SIZES[size]
        digits = _hex_digits(s["w"])
        if decodes.get(size) != (CONST[size], digits, s["h"]):
            probs.append("%s: decode(...) call differs" % size)
            continue
        body = consts.get(CONST[size])
        if body is None:
            probs.append("missing constant %s" % CONST[size])
            continue
        lines = body.rstrip("\n").split("\n")
        if len(lines) != len(scalars):
            probs.append("%s: %d glyph lines for %d scalars" % (size, len(lines), len(scalars)))
            continue
        for k, (cp, line) in enumerate(zip(scalars, lines)):
            e = _ROW_LINE_RE.match(line)
            if not e:
                probs.append("%s: unparsed line %r" % (size, line))
                continue
            hexs, plus, comment = e.group(1), e.group(2), e.group(3)
            last = k == len(scalars) - 1
            if bool(plus) == last:
                probs.append("%s: U+%04X concatenation is wrong" % (size, cp))
            if len(hexs) != digits * s["h"]:
                probs.append("%s: U+%04X has %d hex digits" % (size, cp, len(hexs)))
                continue
            got = [int(hexs[i:i + digits], 16) for i in range(0, len(hexs), digits)]
            if got != vfd_font.GLYPHS[size].get(cp):
                probs.append("%s: U+%04X rows differ" % (size, cp))
            if any(r >> s["w"] for r in got):
                probs.append("%s: U+%04X has bits outside the glyph width" % (size, cp))
            if comment != _char_comment(cp):
                probs.append("%s: U+%04X comment %r" % (size, cp, comment))
        n = sum(len(x) for x in re.findall(r'"([0-9A-F]+)"', body))
        if n * 2 >= 65535:
            probs.append("%s: string constant too long for the class file" % size)
    return probs


def main(argv):
    check = False
    paths = []
    for a in argv:
        if a == "--check":
            check = True
        elif a.startswith("-"):
            print("usage: gen_kotlin.py [OUT.kt] [--check]", file=sys.stderr)
            return 2
        else:
            paths.append(a)
    if len(paths) > 1:
        print("usage: gen_kotlin.py [OUT.kt] [--check]", file=sys.stderr)
        return 2
    path = paths[0] if paths else DEFAULT_OUT
    text = emit_kotlin()
    if check:
        try:
            with open(path, encoding="utf-8", newline="") as f:
                current = f.read()
        except OSError as e:
            print("MISMATCH: cannot read %s: %s" % (path, e), file=sys.stderr)
            return 1
        probs = verify(current)
        if current != text:
            probs.append("%s is out of date: run python3 tools/vfd/gen_kotlin.py" % path)
        if probs:
            for p in probs:
                print("MISMATCH:", p, file=sys.stderr)
            return 1
        print("%s is up to date" % path)
        return 0
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    with open(path, encoding="utf-8") as f:
        probs = verify(f.read())
    if probs:
        for p in probs:
            print("MISMATCH:", p, file=sys.stderr)
        return 1
    n = len(vfd_font.GLYPHS["small"])
    print("wrote %s (%d glyphs x 3 sizes, verified against GLYPHS)" % (path, n))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
